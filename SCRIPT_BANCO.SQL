-- 1. TABELA DE CLIENTES
CREATE TABLE CLIENTE (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(120) NOT NULL,
    DOCUMENTO VARCHAR(20),
    EMAIL VARCHAR(120),
    TELEFONE VARCHAR(30),
    DATACADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. TABELA DE ORDENS DE SERVIÇO
CREATE TABLE ORDEM_SERVICO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENTE_ID INTEGER NOT NULL,
    DATA_ABERTURA DATE NOT NULL,
    DATA_PREVISTA DATE,
    DATA_FECHAMENTO DATE,
    STATUS VARCHAR(15) NOT NULL, -- 'Aberta', 'Em Andamento', 'Concluída', 'Cancelada'
    DESCRICAO_PROBLEMA VARCHAR(500),
    VALOR_TOTAL NUMERIC(15,2) DEFAULT 0.00,
    CONSTRAINT FK_OS_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE(ID)
);

-- 3. TABELA DE ITENS DA ORDEM DE SERVIÇO
CREATE TABLE ITEM_ORDEM (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDEM_ID INTEGER NOT NULL,
    DESCRICAO VARCHAR(200) NOT NULL,
    QUANTIDADE NUMERIC(12,2) NOT NULL,
    VALOR_UNITARIO NUMERIC(15,2) NOT NULL,
    CONSTRAINT FK_ITEM_ORDEM FOREIGN KEY (ORDEM_ID) REFERENCES ORDEM_SERVICO(ID) ON DELETE CASCADE
);

-- 4. BÔNUS (A): HISTÓRICO DE AUDITORIA DE STATUS
CREATE TABLE STATUS_LOG (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDEM_ID INTEGER NOT NULL,
    DATA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS_ANTERIOR VARCHAR(15),
    STATUS_NOVO VARCHAR(15) NOT NULL,
    USUARIO_SIMULADO VARCHAR(50) DEFAULT 'SISTEMA',
    CONSTRAINT FK_LOG_OS FOREIGN KEY (ORDEM_ID) REFERENCES ORDEM_SERVICO(ID) ON DELETE CASCADE
);

-- ÍNDICES PARA ALTA PERFORMANCE NOS FILTROS
CREATE INDEX IDX_OS_STATUS ON ORDEM_SERVICO (STATUS);
CREATE INDEX IDX_OS_CLIENTE ON ORDEM_SERVICO (CLIENTE_ID);
CREATE INDEX IDX_OS_DATA_ABERTURA ON ORDEM_SERVICO (DATA_ABERTURA);

-- VIEW PARA RELATÓRIOS E DASHBOARD
CREATE VIEW VW_OS_RESUMO AS
SELECT
    O.ID,
    O.CLIENTE_ID,
    C.NOME AS CLIENTE_NOME,
    C.DOCUMENTO AS CLIENTE_DOCUMENTO,
    O.DATA_ABERTURA,
    O.DATA_PREVISTA,
    O.DATA_FECHAMENTO,
    O.STATUS,
    O.VALOR_TOTAL,
    CASE
        WHEN (O.STATUS NOT IN ('Concluída', 'Cancelada'))
             AND (O.DATA_PREVISTA IS NOT NULL)
             AND (CURRENT_DATE > O.DATA_PREVISTA)
        THEN 1 ELSE 0
    END AS EM_ATRASO
FROM ORDEM_SERVICO O
JOIN CLIENTE C ON C.ID = O.CLIENTE_ID;

